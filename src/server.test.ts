const PRUSA_GCODE = `; generated by PrusaSlicer 2.8.1
;LAYER_CHANGE
;Z:0.2
G1 X5 Y5 E1
;LAYER_CHANGE
;Z:0.4
G1 X6 Y6 E1
; filament used [mm] = 1234.5
; filament used [g] = 3.7
; estimated printing time (normal mode) = 1h 2m 30s
`;

interface Seen {
    url: string;
    headers: IncomingMessage['headers'];
    body: Buffer;
}

/** A stand-in for api.melt3d.eu answering each request with the next of `answers`. */
async function fakeApi(answers: Array<(res: ServerResponse) => void>): Promise<{ url: string; seen: Seen[]; close(): void }> {
    const seen: Seen[] = [];
    const server = createHttpServer(async (req, res) => {
        const chunks: Buffer[] = [];
        for await (const chunk of req) chunks.push(chunk as Buffer);
        seen.push({ url: req.url ?? '', headers: req.headers, body: gunzipSync(Buffer.concat(chunks)) });
        (answers.shift() ?? ((r) => r.writeHead(500).end()))(res);
    });
    await new Promise<void>((resolve) => server.listen(0, '127.0.0.1', resolve));
    const { port } = server.address() as AddressInfo;
    return { url: `http://127.0.0.1:${port}`, seen, close: () => server.close() };
}

const gcode = (kind = 'full') => (res: ServerResponse) =>
    res.writeHead(200, { 'content-type': 'text/x.gcode', 'x-melt-gcode': kind, 'ratelimit-remaining': '119' }).end(PRUSA_GCODE);

const problem = (status: number, code: string, detail: string, retryAfter?: number) => (res: ServerResponse) =>
    res
        .writeHead(status, {
            'content-type': 'application/problem+json',
            'x-melt-error': code,
            ...(retryAfter ? { 'retry-after': String(retryAfter) } : {}),
        })
        .end(JSON.stringify({ status, code, detail }));

async function connect(apiUrl: string, apiKey: string | undefined = 'm3d_live_x'): Promise<Client> {
    const [clientSide, serverSide] = InMemoryTransport.createLinkedPair();
    await createServer({ apiUrl, apiKey }).connect(serverSide);
    const client = new Client({ name: 'test', version: '0' });
    await client.connect(clientSide);
    return client;
}

async function model(): Promise<string> {
    const dir = await mkdtemp(join(tmpdir(), 'melt3d-mcp-'));
    const path = join(dir, 'bracket.stl');
    await writeFile(path, 'solid bracket\nendsolid bracket\n');
    return path;
}

const text = (result: Awaited<ReturnType<Client['callTool']>>) =>
    (result.content as Array<{ type: string; text: string }>).map((c) => c.text).join('\n');

test('summarizes what the engines write in comments', () => {
    assert.deepEqual(summarize(PRUSA_GCODE), { layers: 2, printSeconds: 3750, filamentGrams: 3.7, filamentMeters: 1.2345 });
    const cura = ';TIME:600\n;Filament used: 2.5m\n;LAYER:0\nG1\n;LAYER:1\n';
    assert.deepEqual(summarize(cura), { layers: 2, printSeconds: 600, filamentGrams: undefined, filamentMeters: 2.5 });
});

test('slice_model writes the G-code beside the model and says what it is', async () => {
    const api = await fakeApi([gcode()]);
    try {
        const client = await connect(api.url);
        const path = await model();
        const result = await client.callTool({ name: 'slice_model', arguments: { model_path: path, layer_height: 0.2, engine: 'prusaslicer' } });
        assert.equal(result.isError, undefined, text(result));
        const output = path.replace(/\.stl$/, '.gcode');
        assert.equal(await readFile(output, 'utf8'), PRUSA_GCODE);
        assert.match(text(result), /printable G-code/);
        assert.match(text(result), /1 h 3 min/);
        assert.deepEqual(result.structuredContent, {
            output_path: output,
            printable: true,
            gcode_bytes: Buffer.byteLength(PRUSA_GCODE),
            layers: 2,
            print_seconds: 3750,
            filament_grams: 3.7,
            filament_meters: 1.2345,
            rate_limit_remaining: 119,
        });

        const [request] = api.seen;
        const url = new URL(request.url, api.url);
        assert.equal(url.pathname, '/v1/slices');
        assert.equal(url.searchParams.get('layer_height'), '0.2');
        assert.equal(url.searchParams.get('filename'), 'bracket.stl');
        assert.equal(request.headers.authorization, 'Bearer m3d_live_x');
        assert.ok(request.headers['idempotency-key']);
        assert.equal(request.body.toString(), 'solid bracket\nendsolid bracket\n');

        const again = await client.callTool({ name: 'slice_model', arguments: { model_path: path } });
        assert.equal(again.isError, true, 'does not overwrite without being asked');
    } finally {
        api.close();
    }
});

test('a test key is told its G-code is a preview', async () => {
    const api = await fakeApi([gcode('preview')]);
    try {
        const client = await connect(api.url, 'm3d_test_x');
        const result = await client.callTool({ name: 'slice_model', arguments: { model_path: await model() } });
        assert.match(text(result), /PREVIEW/);
        assert.equal((result.structuredContent as { printable: boolean }).printable, false);
    } finally {
        api.close();
    }
});

test('the API says why it refused, and the agent hears it', async () => {
    const api = await fakeApi([problem(402, 'payment-required', 'This API key\'s account reached its monthly spending cap.')]);
    try {
        const client = await connect(api.url);
        const result = await client.callTool({ name: 'slice_model', arguments: { model_path: await model() } });
        assert.equal(result.isError, true);
        assert.match(text(result), /spending cap/);
    } finally {
        api.close();
    }
});

test('without a key, the agent is told where to get one', async () => {
    const client = await connect('http://127.0.0.1:9', '');
    const result = await client.callTool({ name: 'slice_model', arguments: { model_path: await model() } });
    assert.equal(result.isError, true);
    assert.match(text(result), /auth\.melt3d\.eu\/developers/);
});

test('only STL files are sent', async () => {
    const client = await connect('http://127.0.0.1:9');
    const path = (await model()).replace(/\.stl$/, '.3mf');
    await writeFile(path, 'x');
    const result = await client.callTool({ name: 'slice_model', arguments: { model_path: path } });
    assert.match(text(result), /not an STL/);
});

test('a busy or rate-limited answer is retried with the same Idempotency-Key', async () => {
    const api = await fakeApi([problem(503, 'busy', 'busy', 1), problem(429, 'rate-limited', 'slow down', 1), gcode()]);
    const waits: number[] = [];
    try {
        const sliced = await slice(
            { apiUrl: api.url, apiKey: 'm3d_live_x', stl: Buffer.from('solid'), filename: 'a.stl', settings: {} },
            async (ms) => {
                waits.push(ms);
            },
        );
        assert.equal(sliced.attempts, 3);
        assert.deepEqual(waits, [1000, 1000], 'waits as Retry-After says');
        const keys = new Set(api.seen.map((s) => s.headers['idempotency-key']));
        assert.equal(keys.size, 1, 'billed once however many times it is sent');
    } finally {
        api.close();
    }
});

test('a request the server will refuse again is not retried', async () => {
    const api = await fakeApi([problem(400, 'out-of-range', 'layer_height 9 is outside 0.01 to 2')]);
    try {
        await assert.rejects(
            slice({ apiUrl: api.url, apiKey: 'm3d_live_x', stl: Buffer.from('solid'), filename: 'a.stl', settings: { layer_height: 9 } }),
            /out-of-range/,
        );
        assert.equal(api.seen.length, 1);
    } finally {
        api.close();
    }
});

test('lists its tools', async () => {
    const client = await connect('http://127.0.0.1:9');
    const { tools } = await client.listTools();
    assert.deepEqual(tools.map((t) => t.name).sort(), ['slice_model', 'slicer_settings']);
});
